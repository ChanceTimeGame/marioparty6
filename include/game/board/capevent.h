/* An event's object list (mbev_CapObjCreate and friends; ev_CapWorkInit). Size 0xB48. */
typedef struct CapObjWork_s {
    /* 0x000 */ int playerMot[64][4];
    /* 0x400 */ int objId[64];
    /* 0x500 */ int sprId[64];
    /* 0x600 */ void *mem[64];
    /* 0x700 */ int objMasuId[64];
    /* 0x800 */ HuVecF objOfs[64];
    /* 0xB00 */ int playerMasuId[4];
    /* 0xB10 */ HuVecF playerOfs[4];
    /* 0xB40 */ s32 bgStatId;
    /* 0xB44 */ OMOBJ *obj;
} CAPOBJWORK;

typedef struct CapFlag_s {
    u8 unk80F : 1;
    u8 kettouF : 1;
    u8 kettouEndF : 1;
    u8 unk10F : 1;
    u8 unk08F : 1;
    u8 unk04F : 1;
    u8 unk02F : 1;
    u8 shockNoWaitF : 1;
} CAPFLAG;

/* The capsule event work: the process property of every capsule event (ev_CapCall copies the
   caller's stack copy into a heap one). Size 0xBF4. */
typedef struct CapWork_s {
    /* 0x000 */ int playerNo;
    /* 0x004 */ int masuPlayer;
    /* 0x008 */ int capsuleNo;
    /* 0x00C */ int masuId;
    /* 0x010 */ int trapMasuId;
    /* 0x014 */ int trapF;
    /* 0x018 */ int moveF;
    /* 0x01C */ int unk1C;
    /* 0x020 */ CAPOBJWORK objWork;
    /* 0xB68 */ CAPFLAG flag;
    /* 0xB69 */ u8 unkB69[3];
    /* 0xB6C */ int objId;
    /* 0xB70 */ u8 unkB70[0xBCC - 0xB70];
    /* 0xBCC */ int procNo;
    /* 0xBD0 */ void *effExplode;
    /* 0xBD4 */ void *effBoost;
    /* 0xBD8 */ void *effSnow;
    /* 0xBDC */ void *effGlow;
    /* 0xBE0 */ void *effRing;
    /* 0xBE4 */ void *effCoin;
    /* 0xBE8 */ void *effCoinMan;
    /* 0xBEC */ void *effStarMan;
    /* 0xBF0 */ void *effCapLose;
} CAPWORK;

/* ev_CapsuleData: one per capsule number. */
typedef struct CapEventData_s {
    /* 0x00 */ void (*func)(void);
    /* 0x04 */ void (*killFunc)(void);
    /* 0x08 */ void (*trapFunc)(CAPWORK *work);
    /* 0x0C */ int statusMode;
    /* 0x10 */ int cameraMode;
    /* 0x14 */ s32 bgDataNum;
    /* 0x18 */ int trapF;
} CAPEVENT_DATA;

